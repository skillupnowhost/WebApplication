          view.reportStyle === "MODERN" && "jd-style-modern",
          COLOR_THEME_CLASS[view.colorTheme],
          printMode ? "shadow-none" : "p-8 shadow-[0_10px_50px_rgba(16,29,58,0.12)] sm:p-10"
